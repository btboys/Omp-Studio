/**
 * Read/write omp's own config.yml through the `omp config` CLI.
 *
 * Why the CLI instead of parsing YAML ourselves: `omp config set` performs
 * type coercion and validation (bad enums are rejected with the valid list),
 * writes nested keys correctly, and survives schema changes between omp
 * versions. The schema itself is machine-readable via `omp config list --json`,
 * so this panel is schema-driven: it renders whatever keys the allowlist below
 * selects, in whatever type omp reports.
 */

export interface OmpConfigEntry {
  key: string;
  type: string;
  /** Resolved value from `omp config list --json`; absent when unset. */
  value?: unknown;
  description: string;
  /** Enum choices, parsed from the human `omp config list` output. */
  options?: string[];
}

export type OmpConfigSectionId = "appearance" | "context" | "files" | "interaction" | "model" | "memory" | "providers" | "advanced";

export interface OmpConfigSection {
  id: OmpConfigSectionId;
  entries: OmpConfigEntry[];
}

