interface SchemaEntry {
  type: string;
  value?: unknown;
  description?: string;
}

function runConfig(args: string[]): Promise<{ stdout: string; stderr: string }> {
  return resolvePiRuntime().then(
    (rt) =>
      new Promise<{ stdout: string; stderr: string }>((resolve, reject) => {
        execFile(
          rt.bin,
          ["config", ...args],
          { timeout: 30000, windowsHide: true },
          (err, stdout, stderr) => {
            if (err) reject(new Error((stderr || stdout || err.message).trim()));
            else resolve({ stdout, stderr });
          },
        );
      }),
  );
}

/** Full curated schema: resolved values + enum options from the omp CLI. */
export async function getOmpConfig(): Promise<OmpConfigSection[]> {
  const [jsonOut, listOut] = await Promise.all([runConfig(["list", "--json"]), runConfig(["list"])]);
  const schema = JSON.parse(jsonOut.stdout.replace(/^\uFEFF/, "").trim()) as Record<string, SchemaEntry>;

  // `omp config list` prints enum keys as `key = value (opt1|opt2|…)`; the JSON
  // schema omits the choices, so recover them from the human output.
  const enumOptions = new Map<string, string[]>();
  for (const line of listOut.stdout.split("\n")) {
    const m = line.match(/^\s*([\w.]+)\s*=\s*\S.*\(([^()]*)\)\s*$/);
    if (m && m[2].includes("|")) {
      enumOptions.set(m[1], m[2].split("|").map((s) => s.trim()).filter(Boolean));
    }
  }

  const sections: OmpConfigSection[] = [];
  for (const group of CONFIG_GROUPS) {
    const entries: OmpConfigEntry[] = [];
    for (const key of group.keys) {
      const s = schema[key];
      if (!s) continue; // key unknown to this omp version → hide
      entries.push({
        key,
        type: s.type,
        value: s.value,
        description: s.description || "",
        options: s.type === "enum" ? enumOptions.get(key) : undefined,
      });
    }
    if (entries.length > 0) sections.push({ id: group.id, entries });
  }
  return sections;
}

function serializeValue(value: unknown, type: string): string {
  if (value === undefined || value === null) return "";
  if (type === "array" || type === "record") return JSON.stringify(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return String(value);
}

export async function setOmpConfigKey(key: string, value: unknown, type: string): Promise<void> {
  await runConfig(["set", key, serializeValue(value, type)]);
}

export async function resetOmpConfigKey(key: string): Promise<void> {
  await runConfig(["reset", key]);
}
